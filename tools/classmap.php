<?php
/**
 * Class map for the autoloader: writes includes/classmap.php from the files in includes/, or checks that it is current.
 *
 *   php tools/classmap.php           write includes/classmap.php
 *   php tools/classmap.php --check   exit 1 when the map is stale or a file breaks the layout rules (CI runs this)
 *
 * Layout rules (the map is only a cache of them, so a file that follows them is found even before the map is rebuilt):
 *  - every PHP file under includes/<folder>/ declares exactly one class, trait or interface in namespace LaunchBuilder;
 *  - LaunchBuilder\Foo_Bar lives in includes/<folder>/class-foo-bar.php (a trait in trait-foo-bar.php, an interface in
 *    interface-foo-bar.php);
 *  - a class name is used once across all folders.
 * Runs without WordPress (plain PHP 7.4+).
 */

$root  = dirname( __DIR__ );
$check = in_array( '--check', array_slice( $argv, 1 ), true );
$map   = [];
$errors = [];

$files = glob( $root . '/includes/*/*.php' ) ?: [];
sort( $files );
foreach ( glob( $root . '/includes/*.php' ) ?: [] as $loose ) {
	if ( 'classmap.php' !== basename( $loose ) ) {
		$errors[] = 'includes/' . basename( $loose ) . ': class files live in a folder under includes/ (see docs/ARCHITECTURE.md).';
	}
}
foreach ( $files as $file ) {
	$rel = substr( $file, strlen( $root ) + 1 );
	$tokens = token_get_all( (string) file_get_contents( $file ) );
	$found = [];
	$namespace = '';
	for ( $i = 0, $n = count( $tokens ); $i < $n; $i++ ) {
		if ( ! is_array( $tokens[ $i ] ) ) {
			continue;
		}
		if ( T_NAMESPACE === $tokens[ $i ][0] ) {
			for ( $j = $i + 1; $j < $n && ';' !== $tokens[ $j ]; $j++ ) {
				$namespace .= is_array( $tokens[ $j ] ) ? trim( $tokens[ $j ][1] ) : '';
			}
		}
		if ( in_array( $tokens[ $i ][0], [ T_CLASS, T_TRAIT, T_INTERFACE ], true ) ) {
			$prev = $i - 1;
			while ( $prev >= 0 && is_array( $tokens[ $prev ] ) && T_WHITESPACE === $tokens[ $prev ][0] ) {
				$prev--;
			}
			if ( $prev >= 0 && is_array( $tokens[ $prev ] ) && in_array( $tokens[ $prev ][0], [ T_DOUBLE_COLON, T_NEW ], true ) ) {
				continue; // Foo::class or new class.
			}
			$j = $i + 1;
			while ( is_array( $tokens[ $j ] ) && T_WHITESPACE === $tokens[ $j ][0] ) {
				$j++;
			}
			if ( is_array( $tokens[ $j ] ) && T_STRING === $tokens[ $j ][0] ) {
				$kind = T_CLASS === $tokens[ $i ][0] ? 'class' : ( T_TRAIT === $tokens[ $i ][0] ? 'trait' : 'interface' );
				$found[] = [ $kind, $tokens[ $j ][1] ];
			}
		}
	}
	if ( 1 !== count( $found ) ) {
		$errors[] = $rel . ': declares ' . count( $found ) . ' classes; one per file.';
		continue;
	}
	[ $kind, $name ] = $found[0];
	if ( 'LaunchBuilder' !== $namespace ) {
		$errors[] = $rel . ': namespace must be LaunchBuilder (found "' . $namespace . '").';
	}
	$want = $kind . '-' . strtolower( str_replace( '_', '-', $name ) ) . '.php';
	if ( basename( $file ) !== $want ) {
		$errors[] = $rel . ': ' . $kind . ' ' . $name . ' belongs in a file named ' . $want . '.';
	}
	if ( isset( $map[ $name ] ) ) {
		$errors[] = $rel . ': ' . $name . ' is already declared in includes/' . $map[ $name ] . '.';
	}
	$map[ $name ] = substr( $rel, strlen( 'includes/' ) );
}
ksort( $map );

$out = "<?php\n// Generated by tools/classmap.php from the files in includes/: do not edit by hand (php tools/classmap.php rewrites it).\n// Class (short name, namespace LaunchBuilder) => file under includes/. Read by the autoloader in launch-builder.php.\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn [\n";
$width = $map ? max( array_map( 'strlen', array_keys( $map ) ) ) + 2 : 0;
foreach ( $map as $name => $path ) {
	$out .= "\t" . str_pad( "'" . $name . "'", $width ) . " => '" . $path . "',\n";
}
$out .= "];\n";

$target = $root . '/includes/classmap.php';
if ( $check ) {
	if ( ! is_file( $target ) || file_get_contents( $target ) !== $out ) {
		$errors[] = 'includes/classmap.php is out of date: run php tools/classmap.php and commit the result.';
	}
	if ( $errors ) {
		fwrite( STDERR, implode( "\n", $errors ) . "\n" );
		exit( 1 );
	}
	echo count( $map ) . " classes, map up to date.\n";
	exit( 0 );
}
if ( $errors ) {
	fwrite( STDERR, implode( "\n", $errors ) . "\n" );
	exit( 1 );
}
file_put_contents( $target, $out );
echo 'Wrote includes/classmap.php (' . count( $map ) . " classes).\n";
